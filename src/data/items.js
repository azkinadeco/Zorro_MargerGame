// Helper to pick random item from generator spawn table
export function getSpawnItem(generatorId) {
  const gen = ITEMS[generatorId];
  if (!gen || !gen.spawns) return 'food_1';

  const totalWeight = gen.spawns.reduce((sum, item) => sum + item.weight, 0);
  let randomNum = Math.random() * totalWeight;

  for (const spawn of gen.spawns) {
    if (randomNum < spawn.weight) {
      return spawn.id;
    }
    randomNum -= spawn.weight;
  }
  return gen.spawns[0].id;
}
